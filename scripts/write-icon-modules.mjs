import fs from "node:fs/promises";
import path from "node:path";

const pascal = (name) => name.split("-").map((word) => word[0].toUpperCase() + word.slice(1)).join("");
const namedAliases = {
  AlertCircle: "circle-alert", AlertTriangle: "triangle-alert", BarChart3: "chart-column",
  CheckCircle: "circle-check-big", CheckCircle2: "circle-check", CircleHelp: "circle-question-mark",
  DownloadCloud: "cloud-download", Filter: "funnel", Loader2: "loader-circle",
  MoreHorizontal: "ellipsis", MoreVertical: "ellipsis-vertical", XCircle: "circle-x",
};

function componentModule(name, mapping, variants) {
  let module = `// Generated by scripts/build-icon-assets.mjs.\nimport { createArtworkIcon } from "./create-artwork-icon";\nimport { artwork } from "./artwork/${mapping.source}";\n`;
  const options = [];
  for (const [kind, source] of Object.entries(variants)) {
    module += `import { artwork as ${kind} } from "./artwork/${source}";\n`;
    options.push(kind);
  }
  if (mapping.rotation) options.push(`rotation: ${mapping.rotation}`);
  return module + `export default /* @__PURE__ */ createArtworkIcon(${JSON.stringify(name)}, artwork${options.length ? `, { ${options.join(", ")} }` : ""});\n`;
}

async function writeComponents(root, names, contract) {
  const mappings = new Map(contract.runtime.map((item) => [item.name, item]));
  for (const name of names) {
    const mapping = mappings.get(name) ?? { source: name, rotation: 0 };
    if (!contract.requiredSourceNames.includes(mapping.source)) continue;
    const module = componentModule(name, mapping, contract.variants[mapping.source] ?? {});
    await fs.writeFile(path.join(root, `src/icons/${name}.tsx`), module);
  }
}

async function writeAliases(root, names, aliases) {
  for (const [alias, name] of Object.entries(aliases)) {
    if (names.includes(name)) await fs.writeFile(path.join(root, `src/icons/${alias}.tsx`), `export { default } from "./${name}";\n`);
  }
}

async function writeBarrel(root, names) {
  const named = new Map(names.map((name) => [pascal(name), name]));
  for (const [alias, name] of Object.entries(namedAliases)) if (names.includes(name)) named.set(alias, name);
  const barrel = [...named].map(([symbol, name]) => `export { default as ${symbol} } from "./${name}";`).join("\n");
  await fs.writeFile(path.join(root, "src/icons/index.ts"), barrel + '\nexport type { IconProps, ArtworkIconComponent } from "./create-artwork-icon";\n');
}

async function writeRegistry(root, names, aliases) {
  const loaders = [...names.map((name) => [name, name]), ...Object.entries(aliases).filter(([, name]) => names.includes(name))];
  await fs.writeFile(path.join(root, "src/icons/registry.ts"), `import type { ArtworkIconComponent } from "./create-artwork-icon";\n\nconst loaders = {\n${loaders.map(([key, name]) => `  ${JSON.stringify(key)}: () => import("./${name}"),`).join("\n")}\n};\n\nexport type IconName = keyof typeof loaders;\n\nexport function isIconName(name: unknown): name is IconName {\n  return typeof name === "string" && Object.hasOwn(loaders, name);\n}\n\nexport async function loadIcon(name: unknown): Promise<ArtworkIconComponent | null> {\n  if (!isIconName(name)) return null;\n  return (await loaders[name]()).default;\n}\n`);
}

/** Keep the existing public catalogue while sharing only audited source designs. */
export async function writeIconModules(root, contract, legacy) {
  const names = [...new Set([...legacy.groups.flatMap((group) => group.names).filter(Boolean), ...contract.requiredSourceNames, ...contract.runtime.map((item) => item.name)])];
  const aliases = { ...legacy.aliases, "bar-chart3": "chart-column", "circle-help": "circle-question-mark", building2: "building-2", settings2: "settings-2", trash2: "trash-2" };
  await writeComponents(root, names, contract);
  await writeAliases(root, names, aliases);
  await writeBarrel(root, names);
  await writeRegistry(root, names, aliases);
}
