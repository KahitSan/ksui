import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import sharp from "sharp";
import { chooseArtwork } from "./trace-icon-artwork.mjs";

const root = fileURLToPath(new URL("../", import.meta.url));
const sourceRoot = path.join(root, "assets/icon-sources");
const outputRoot = path.join(root, "assets/icon-exports");
const artworkRoot = path.join(root, "src/icons/artwork");
const manifest = JSON.parse(
  await fs.readFile(path.join(sourceRoot, "manifest.json"), "utf8")
);
const onlyAvailable = process.argv.includes("--available");
const edge = 144;
await fs.mkdir(outputRoot, { recursive: true });
await fs.mkdir(artworkRoot, { recursive: true });
const results = [];

for (const group of manifest.groups) {
  const file = path.join(sourceRoot, `${group.id}-original.png`);
  if (onlyAvailable) {
    try {
      await fs.access(file);
    } catch {
      continue;
    }
  }
  const { data, info } = await sharp(file)
    .ensureAlpha()
    .raw()
    .toBuffer({ resolveWithObject: true });
  for (let index = 0; index < group.names.length; index++) {
    const name = group.names[index];
    const column = index % group.columns;
    const row = Math.floor(index / group.columns);
    const left = Math.round((column * info.width) / group.columns);
    const top = Math.round((row * info.height) / group.rows);
    const right = Math.round(((column + 1) * info.width) / group.columns);
    const bottom = Math.round(((row + 1) * info.height) / group.rows);
    let x0 = right,
      y0 = bottom,
      x1 = -1,
      y1 = -1;
    for (let y = top; y < bottom; y++) {
      for (let x = left; x < right; x++) {
        if (data[(y * info.width + x) * 4 + 3] > 16) {
          x0 = Math.min(x0, x);
          y0 = Math.min(y0, y);
          x1 = Math.max(x1, x);
          y1 = Math.max(y1, y);
        }
      }
    }
    if (x1 < x0 || y1 < y0) throw new Error(`Empty artwork: ${name}`);
    if (
      x0 <= left + 1 ||
      y0 <= top + 1 ||
      x1 >= right - 2 ||
      y1 >= bottom - 2
    ) {
      throw new Error(`Artwork crosses its cell boundary: ${name}`);
    }
    // Preserve a two-pixel edge around faint antialiasing before normalizing.
    x0 = Math.max(left, x0 - 2);
    y0 = Math.max(top, y0 - 2);
    x1 = Math.min(right - 1, x1 + 2);
    y1 = Math.min(bottom - 1, y1 + 2);
    const normalized = await sharp(file)
      .extract({ left: x0, top: y0, width: x1 - x0 + 1, height: y1 - y0 + 1 })
      .resize((edge * 5) / 6, (edge * 5) / 6, {
        fit: "contain",
        background: { r: 0, g: 0, b: 0, alpha: 0 },
      })
      .extend({
        top: edge / 12,
        bottom: edge / 12,
        left: edge / 12,
        right: edge / 12,
        background: { r: 0, g: 0, b: 0, alpha: 0 },
      })
      .ensureAlpha()
      .raw()
      .toBuffer({ resolveWithObject: true });
    // Only alpha is rendered. Constant white RGB allows lossless palette encoding.
    for (let pixel = 0; pixel < normalized.data.length; pixel += 4) {
      normalized.data[pixel] = 255;
      normalized.data[pixel + 1] = 255;
      normalized.data[pixel + 2] = 255;
    }
    const raw = normalized.data;
    const encode = () => sharp(raw, { raw: normalized.info });
    let png = await encode()
      .png({
        palette: true,
        colours: 256,
        dither: 0,
        quality: 100,
        compressionLevel: 9,
      })
      .toBuffer();
    const alpha = Buffer.from(raw.filter((_, index) => index % 4 === 3));
    const decoded = await sharp(png)
      .ensureAlpha()
      .extractChannel("alpha")
      .raw()
      .toBuffer();
    const paletteExact = decoded.equals(alpha);
    if (!paletteExact)
      png = await encode().png({ compressionLevel: 9 }).toBuffer();
    const roundTrip = await sharp(png)
      .ensureAlpha()
      .extractChannel("alpha")
      .raw()
      .toBuffer();
    if (!roundTrip.equals(alpha))
      throw new Error(`Non-lossless alpha encoding: ${name}`);
    await fs.writeFile(path.join(outputRoot, `${name}.png`), png);
    const chosen = await chooseArtwork(png, alpha, edge);
    await fs.writeFile(path.join(outputRoot, `${name}.svg`), chosen.svg);
    await fs.writeFile(
      path.join(artworkRoot, `${name}.ts`),
      `// Generated by scripts/build-icon-assets.mjs.\nexport const artwork = ${JSON.stringify(
        chosen.artwork
      )};\n`
    );
    results.push({
      name,
      group: group.id,
      originalCell: { left, top, right, bottom },
      crop: { x0, y0, x1, y1 },
      width: edge,
      height: edge,
      bytes: png.length,
      paletteExact,
      decodedBytes: raw.length,
      delivery: chosen.metrics,
    });
  }
}

await fs.writeFile(
  path.join(outputRoot, "metrics.generated.json"),
  JSON.stringify({ edge, icons: results }, null, 2) + "\n"
);

const names = results.map((icon) => icon.name);
const pascal = (name) =>
  name
    .split("-")
    .map((word) => word[0].toUpperCase() + word.slice(1))
    .join("");
const aliases = {
  ...manifest.aliases,
  "bar-chart3": "chart-column",
  "circle-help": "circle-question-mark",
  building2: "building-2",
  settings2: "settings-2",
  trash2: "trash-2",
};
const namedAliases = {
  AlertCircle: "circle-alert",
  AlertTriangle: "triangle-alert",
  BarChart3: "chart-column",
  CheckCircle: "circle-check-big",
  CheckCircle2: "circle-check",
  CircleHelp: "circle-question-mark",
  DownloadCloud: "cloud-download",
  Filter: "funnel",
  Loader2: "loader-circle",
  MoreHorizontal: "ellipsis",
  MoreVertical: "ellipsis-vertical",
  XCircle: "circle-x",
};
const named = new Map(names.map((name) => [pascal(name), name]));
for (const [alias, name] of Object.entries(namedAliases))
  if (names.includes(name)) named.set(alias, name);
for (const name of names) {
  const variant =
    name === "check"
      ? "check-bold"
      : name === "circle-check"
      ? "circle-check-bold"
      : name === "star"
      ? "star-filled"
      : null;
  const option = name === "star" ? "filled" : "bold";
  let module = `// Generated by scripts/build-icon-assets.mjs.\nimport { createArtworkIcon } from "./create-artwork-icon";\nimport { artwork } from "./artwork/${name}";\n`;
  if (variant && names.includes(variant))
    module += `import { artwork as variant } from "./artwork/${variant}";\n`;
  module += `export default /* @__PURE__ */ createArtworkIcon(${JSON.stringify(
    name
  )}, artwork${
    variant && names.includes(variant) ? `, { ${option}: variant }` : ""
  });\n`;
  await fs.writeFile(path.join(root, `src/icons/${name}.tsx`), module);
}
for (const [alias, name] of Object.entries(aliases))
  if (names.includes(name)) {
    await fs.writeFile(
      path.join(root, `src/icons/${alias}.tsx`),
      `export { default } from "./${name}";\n`
    );
  }
const barrel = [...named]
  .map(([symbol, name]) => `export { default as ${symbol} } from "./${name}";`)
  .join("\n");
await fs.writeFile(
  path.join(root, "src/icons/index.ts"),
  barrel +
    '\nexport type { IconProps, ArtworkIconComponent } from "./create-artwork-icon";\n'
);
const loaders = [
  ...names.map((name) => [name, name]),
  ...Object.entries(aliases).filter(([, name]) => names.includes(name)),
];
const registry = `import type { ArtworkIconComponent } from "./create-artwork-icon";\n\nconst loaders = {\n${loaders
  .map(([key, name]) => `  ${JSON.stringify(key)}: () => import("./${name}"),`)
  .join(
    "\n"
  )}\n};\n\nexport type IconName = keyof typeof loaders;\n\nexport function isIconName(name: string): name is IconName {\n  return Object.hasOwn(loaders, name);\n}\n\nexport async function loadIcon(name: string): Promise<ArtworkIconComponent | null> {\n  if (!isIconName(name)) return null;\n  return (await loaders[name]()).default;\n}\n`;
await fs.writeFile(path.join(root, "src/icons/registry.ts"), registry);
console.log(
  JSON.stringify(
    {
      icons: results.length,
      bytes: results.reduce((n, icon) => n + icon.bytes, 0),
      largest: results.toSorted((a, b) => b.bytes - a.bytes).slice(0, 5),
    },
    null,
    2
  )
);
